// node tools/build-i18n.cjs <strings-da.json>  -> writes src/i18n-da.js (the Danish table, generated - edit the JSON, not the output)
// Workflow: node tools/extract-strings.cjs > strings-en.json, translate the new entries, then run this.
const fs = require('fs'), path = require('path');
const src = process.argv[2]; if (!src) { console.error('usage: node tools/build-i18n.cjs <strings-da.json>'); process.exit(1); }
const table = JSON.parse(fs.readFileSync(src, 'utf8'));
const keys = Object.keys(table).sort();
let bad = 0;
for (const k of keys) {                                   // every template placeholder in the translation must exist in the English
  const a = new Set((k.match(/\{\d+\}/g) || [])), b = (table[k].match(/\{\d+\}/g) || []);
  for (const p of b) if (!a.has(p)) { console.error('placeholder ' + p + ' not in: ' + k); bad++; }
}
if (bad) process.exit(1);
const out = '// Danish translations of the user-interface texts. GENERATED by tools/build-i18n.cjs from a JSON table - do not edit by hand.\n' +
  'export const DA = ' + JSON.stringify(Object.fromEntries(keys.map((k) => [k, table[k]])), null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'i18n-da.js'), out);
console.log('wrote src/i18n-da.js with ' + keys.length + ' entries');
